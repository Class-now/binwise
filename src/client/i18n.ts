export const STRINGS: Record<Language, Record<Key, string>> = { en, ja, zh, ko, vi, ne };

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && (LANGUAGES as readonly string[]).includes(value);
}

/** Looks up a UI string and fills {placeholders}. */
export function t(lang: Language, key: Key, vars: Record<string, string | number> = {}): string {
  const text = STRINGS[lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Browser language → supported UI language. */
export function detectLanguage(preferred: readonly string[]): Language {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split("-")[0];
    if (isLanguage(base)) return base;
  }
  return "en";
}
